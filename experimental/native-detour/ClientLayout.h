// Require a complete small span to belong to the verified image's mapped allocation.
inline bool ImageContains(std::uintptr_t image, std::uintptr_t address, std::size_t size) noexcept {
    MEMORY_BASIC_INFORMATION region{};
    if (address < image || VirtualQuery(reinterpret_cast<const void*>(address), &region, sizeof(region)) != sizeof(region) ||
        region.State != MEM_COMMIT || region.Type != MEM_IMAGE || reinterpret_cast<std::uintptr_t>(region.AllocationBase) != image)
        return false;
    const auto offset = address - reinterpret_cast<std::uintptr_t>(region.BaseAddress);
    return offset < region.RegionSize && size <= region.RegionSize - offset;
}

// Compare the exact entry bytes from the verified image before using a native function.
template<std::size_t Length>
bool MatchesImageEntry(std::uintptr_t image, const FunctionEntry<Length>& entry) noexcept {
    const auto address = image + entry.rva;
    std::array<unsigned char, Length> actual{};
    return ImageContains(image, address, Length) &&
        dingtalkbridge::native::payload::detail::safe_read(reinterpret_cast<const void*>(address), actual.data(), Length) &&
        actual == entry.bytes;
}

